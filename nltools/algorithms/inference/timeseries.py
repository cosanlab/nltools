"""Permutation tests for autocorrelated time series.

Shuffling the samples of a time series destroys its autocorrelation and inflates
false positives. These surrogate-data methods build the null while preserving
temporal structure:

- `circle_shift`: rotate the series (preserves autocorrelation exactly)
- `phase_randomize`: randomize Fourier phases (preserves the power spectrum)
- `timeseries_correlation_permutation_test`: correlation test using either method

`device` selects the execution path: `'cpu'` (default) spreads permutations across
`n_jobs` workers, `'gpu'` vectorizes them in memory-bounded batches, `None` runs
single-threaded.

References:
    Theiler, J., Galdrikian, B., Longtin, A., Eubank, S., & Farmer, J. D. (1991).
    Testing for nonlinearity in time series: the method of surrogate data
    (No. LA-UR-91-3343; CONF-9108181-1). Los Alamos National Lab., NM (United States).

    Lancaster, G., Iatsenko, D., Pidde, A., Ticcinelli, V., & Stefanovska, A. (2018).
    Surrogate data for hypothesis testing of physical systems. Physics Reports, 748, 1-60.
"""

