# ---------------------------------------------------------------------------
# Reserved column namespace
# ---------------------------------------------------------------------------

RESERVED_PREFIX = ".nl_"
"""Prefix marking a column name generated by nltools rather than the user.

Every column nltools invents — polynomial drift (`.nl_poly_0`), DCT cosine
bases (`.nl_cosine_1`), spike indicators (`.nl_global_spike1`), and the
run-separated variants produced by a multi-run `DesignMatrix.append` — carries
this prefix. Machinery that needs to recognize its own columns keys on the
prefix, never on heuristics over user-controlled names (underscore counts,
substring matches), so users may name their own regressors anything without
colliding with nltools internals.
"""

_RUN_SEPARATED_RE = re.compile(re.escape(RESERVED_PREFIX) + r"r(\d+)_(.+)")


def reserved_name(base: str) -> str:
    """Build a generated column name inside the reserved namespace.

    Args:
        base: Name without the reserved prefix, e.g. ``'poly_0'``.

    Returns:
        str: `base` prefixed with `RESERVED_PREFIX`, idempotently — a name
            that already carries the prefix is returned unchanged.
    """
    return base if is_reserved_name(base) else f"{RESERVED_PREFIX}{base}"


def is_reserved_name(name: str) -> bool:
    """Return True if ``name`` is in the nltools-generated column namespace."""
    return name.startswith(RESERVED_PREFIX)


def strip_reserved_prefix(name: str) -> str:
    """Return ``name`` without its reserved prefix (a no-op if it has none)."""
    return name[len(RESERVED_PREFIX) :] if is_reserved_name(name) else name


def run_separated_name(run_idx: int, name: str) -> str:
    """Build the run-separated variant of a column name.

    Run separation is an nltools-generated naming decision, so the result
    always lands in the reserved namespace regardless of whether the source
    column was user-named (``motion_x`` → ``.nl_r0_motion_x``) or already
    generated (``.nl_poly_0`` → ``.nl_r0_poly_0``; prefixes never stack).

    Args:
        run_idx: Zero-based run index.
        name: Column name to separate.

    Returns:
        str: ``.nl_r{run_idx}_{base}``.
    """
    return f"{RESERVED_PREFIX}r{run_idx}_{strip_reserved_prefix(name)}"


def parse_run_separated(name: str) -> tuple[int, str] | None:
    """Split a run-separated column name into its run index and base name.

    Args:
        name: Column name to parse.

    Returns:
        tuple[int, str] | None: `(run_idx, base)` for a run-separated name (e.g.
            `'.nl_r1_poly_0'` → `(1, 'poly_0')`), else None.
    """
    match = _RUN_SEPARATED_RE.fullmatch(name)
    return (int(match.group(1)), match.group(2)) if match else None


