class _NullProgressBar:
    """No-op stand-in for `tqdm` used when `progress_bar=False`.

    Supports the subset of the tqdm interface nltools relies on, so call sites
    that drive a bar manually need no branching.
    """

    def update(self, n: int = 1) -> None:
        pass

    def close(self) -> None:
        pass

    def set_postfix(self, *args, **kwargs) -> None:
        pass

    def set_description(self, *args, **kwargs) -> None:
        pass

    def __enter__(self) -> "_NullProgressBar":
        return self

    def __exit__(self, *exc_info) -> bool:
        return False


def maybe_tqdm(iterable, *, progress_bar: bool, **tqdm_kwargs):
    """Wrap `iterable` in a tqdm progress bar only when `progress_bar` is True.

    tqdm writes to stderr, so an unconditional bar makes functions noisy when
    called in a loop (a 100-iteration calibration study would emit 100 bars).
    Importing tqdm lazily also keeps it off the import path when unused. Uses
    `tqdm.auto`, so notebooks get widget bars and terminals get text bars.

    Args:
        iterable (Iterable): The iterable to wrap.
        progress_bar (bool): Whether to display a progress bar.
        **tqdm_kwargs (dict): Forwarded to `tqdm` (e.g. `desc`, `unit`, `total`).

    Returns:
        Iterable: The original iterable, or a `tqdm`-wrapped version of it.

    Examples:
        ```python
        for i in maybe_tqdm(range(n_permute), progress_bar=progress_bar,
                            desc="CPU parallel perms", unit="perm"):
            ...
        ```
    """
    if not progress_bar:
        return iterable

    from tqdm.auto import tqdm

    return tqdm(iterable, **tqdm_kwargs)


def make_progress_bar(*, progress_bar: bool, **tqdm_kwargs):
    """Build a progress bar, or a no-op stand-in when `progress_bar` is False.

    Use this for call sites that drive the bar manually via `.update()` rather
    than by iteration. Uses `tqdm.auto`, so notebooks get widget bars and
    terminals get text bars.

    Args:
        progress_bar (bool): Whether to display a progress bar.
        **tqdm_kwargs (dict): Forwarded to `tqdm` (e.g. `total`, `desc`, `unit`).

    Returns:
        tqdm | _NullProgressBar: A `tqdm` instance, or a `_NullProgressBar` exposing
            the same subset of its interface (`update`, `close`, `set_postfix`,
            `set_description`, and the context-manager protocol).
    """
    if not progress_bar:
        return _NullProgressBar()

    from tqdm.auto import tqdm

    return tqdm(**tqdm_kwargs)


def resolve_threshold(value, data):
    """Resolve a threshold spec — a number or a percentile string — to a float.

    The single source of truth for what `"98%"` means across the library
    (`BrainData.threshold` and `BrainData.iplot` both route through it).
    Numbers and None pass through unchanged. A percentile string is resolved
    against the **finite nonzero** values of `data`: on a masked stat map
    most voxels are exactly zero (absence of data), and including them drags
    every percentile toward zero.

    Args:
        value: A number (returned as-is), None (returned as-is), or a string
            like `"98%"`.
        data: Array-like the percentile is computed over. Callers choose the
            frame of reference — e.g. `iplot` passes magnitudes
            (`np.abs(data)`) because its window is a magnitude window, while
            `threshold` passes signed values.

    Returns:
        float | None: The resolved threshold.

    Raises:
        ValueError: If `value` is a string without a trailing `%`.
    """
    import numpy as np

    if value is None or not isinstance(value, str):
        return value
    if not value.endswith("%"):
        raise ValueError(
            f"string threshold must be a percentile like '98%', got {value!r}"
        )
    pct = float(value[:-1])
    vals = np.asarray(data, dtype=float).ravel()
    vals = vals[np.isfinite(vals)]
    vals = vals[vals != 0]
    if vals.size == 0:
        return 0.0
    return float(np.percentile(vals, pct))
